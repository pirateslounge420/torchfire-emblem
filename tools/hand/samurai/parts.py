"""Samurai v4 — hand-pixelled PARTS, stamped together per frame by frames.py.

Every part is a list of strings, one character per pixel, '?' = leave alone.
Letters are the palette in frames.py; 'o' is the outline. Parts face LEFT.
The figure is ~58 px tall: head 20, torso 16, legs 24 (hakama + shoes).

The gi is near-black ('k') lit from the upper-left: 'c' on the lit planes, a
1-px 'g' rim on the top edges — jewel tone on dark, the card-art register.
"""


def _check(part, name):
    w = len(part[0])
    for r in part:
        assert len(r) == w, f"{name}: row width {len(r)} != {w}: {r}"
    return part


